// Explicit, NOT `device->swapchainFormat()` -- see tonemap_linear.frag.
// slang's own header comment: this tool's own tonemap shader does its OWN
// explicit `pow(x, 1/2.2)` sRGB encode, so the backbuffer attachment MUST
// be a plain UNORM format (no hardware sRGB re-encode on write, which
// would double-encode against an _SRGB attachment).
constexpr VkFormat kBackbufferFormat = VK_FORMAT_R8G8B8A8_UNORM;

// Matches harness.html's own `state.renderingParameters.clearColor =
// [0.22, 0.25, 0.29, 1.0]` -- an SRGB-DOMAIN literal (what both sides'
// own tonemap paths ultimately write to their 8-bit backbuffer for an
// untouched background pixel). This tool's own forward pass clears its
// LINEAR HDR target, so the literal must be converted back to linear
// first (pow(c, 2.2)) -- the inverse of tonemap_linear.frag.slang's own
// `pow(clamped, 1/2.2)` -- so that after THIS tool's own tonemap pass
// re-applies that forward encode, the final 8-bit value matches the
// reference's literal exactly (up to encode/decode rounding).
float srgbLiteralToLinear(float c) { return std::pow(c, 2.2F); }
const VkClearColorValue kConformanceClearColor{
    {srgbLiteralToLinear(0.22F), srgbLiteralToLinear(0.25F), srgbLiteralToLinear(0.29F), 1.0F}};

