int main(int argc, char** argv) {
    auto args = parseArgs(argc, argv);
    if (!args.has_value()) {
        return 1;
    }

    const rx::conformance::ConformanceModel* model = rx::conformance::findConformanceModel(args->model);
    if (model == nullptr) {
        RX_LOG_ERROR("rx_conformance_render: unknown --model '{}' (see tests/conformance/models.h)", args->model);
        return 1;
    }

    const std::filesystem::path repoRoot(RX_REPO_ROOT_DIR);
    const std::filesystem::path scenePath =
        repoRoot / "assets" / "fetched" / model->name / "glTF" / (model->name + ".gltf");
    const std::filesystem::path referencePath = repoRoot / "tests" / "conformance" / "references" / model->name / "reference.png";
    const std::filesystem::path envPath = repoRoot / "samples" / "08_gltf_viewer" / "environments" / "gate_test_env.hdr";

    if (!std::filesystem::exists(scenePath) || !std::filesystem::exists(referencePath)) {
        if (model->optional) {
            RX_LOG_INFO(
                "rx_conformance_render: '{}' not fetched/referenced locally (optional model -- run "
                "tools/fetch_assets.sh --environment-test and tools/gltf_conformance/generate_reference.mjs "
                "{} to exercise it) -- skipping",
                model->name, model->name);
            return 0;
        }
        RX_LOG_ERROR("rx_conformance_render: '{}' or '{}' not found -- run tools/fetch_assets.sh first",
                     scenePath.string(), referencePath.string());
        return 1;
    }

    auto app = makeApp(args->validate);
    if (app == nullptr) {
        return 1;
    }

    const std::filesystem::path iblShaderDir = repoRoot / "shaders" / "ibl";
    if (!setupEnvironment(*app, envPath, iblShaderDir, /*intensity=*/1.0F)) {
        RX_LOG_ERROR("rx_conformance_render: setupEnvironment failed");
        destroyApp(*app);
        return 1;
    }

    rx::task::Scheduler& scheduler = *app->scheduler;
    rx::asset::ImportResult result =
        app->registry->importGltf(scenePath, *app->geometryPool, scheduler, app->textureCache.get());
    if (!result.ok()) {
        RX_LOG_ERROR("rx_conformance_render: import of '{}' failed: {}", scenePath.string(),
                     rx::asset::importErrorName(result.error));
        destroyApp(*app);
        return 1;
    }

    // +1: headroom for the on-demand D11/D24 FALLBACK material binding
    // buildDrawList() below may need (glTF's own "primitive.material is
    // OPTIONAL -- use the default material when absent" rule -- see that
    // function's own comment). At most ONE extra binding is ever needed
    // regardless of how many material-less submeshes exist: every such
    // submesh resolves to the SAME fallback MaterialHandle, and
    // buildDrawList()'s own materialHandleToBinding lookup memoizes it
    // after the first bind.
    if (!createMaterialParamArena(*app, static_cast<uint32_t>(result.materials.size()) + 1)) {
        destroyApp(*app);
        return 1;
    }
    if (!setupMaterials(*app, *app->registry, result.materials, args->perturbRoughness)) {
        destroyApp(*app);
        return 1;
    }
    if (!buildDrawList(*app, *app->registry, result.scene)) {
        destroyApp(*app);
        return 1;
    }
    // [camera_fit.h's own accumulateReferenceStyleSceneExtents() header
    // comment -- load-bearing, not a plain tight union] PER-PRIMITIVE
    // (submesh) world bounds, exactly the granularity the reference
    // renderer's own getSceneExtents() operates at.
    std::vector<rx::asset::AABB> perPrimitiveWorldBounds;
    for (const rx::asset::InstanceRecord& instance : result.scene.instances) {
        const rx::asset::MeshAsset& mesh = app->registry->mesh(instance.mesh);
        for (const rx::asset::Submesh& submesh : mesh.submeshes) {
            perPrimitiveWorldBounds.push_back(submesh.bounds.transformed(instance.worldTransform));
        }
    }
    const rx::asset::AABB referenceStyleExtents =
        rx::conformance::accumulateReferenceStyleSceneExtents(perPrimitiveWorldBounds);

    const float aspect = static_cast<float>(kRenderWidth) / static_cast<float>(kRenderHeight);
    const rx::conformance::CameraFit fit = rx::conformance::fitCameraToScene(referenceStyleExtents, aspect);

    rx::scene::Camera reversedZCamera;
    reversedZCamera.verticalFovRadians = fit.yfovRadians;
    reversedZCamera.aspectRatio = aspect;
    reversedZCamera.nearPlane = fit.znear;
    reversedZCamera.cullingFarPlane = fit.zfar;
    const glm::mat4 proj = reversedZCamera.cullingProj();
    const glm::mat4 view = glm::lookAt(fit.position, fit.target, glm::vec3(0.0F, 1.0F, 0.0F));
    const glm::mat4 viewProj = proj * view;
    updateDrawDataPerPassFields(*app, viewProj, fit.position);

    VkPhysicalDeviceProperties deviceProps{};
    vkGetPhysicalDeviceProperties(app->device->physicalDevice(), &deviceProps);
    RX_LOG_INFO(
        "rx_conformance_render: model='{}' driver='{}' camera(pos=({:.3f},{:.3f},{:.3f}) "
        "target=({:.3f},{:.3f},{:.3f}) yfov={:.4f} near={:.4f} far={:.4f})",
        model->name, deviceProps.deviceName, fit.position.x, fit.position.y, fit.position.z, fit.target.x,
        fit.target.y, fit.target.z, fit.yfovRadians, fit.znear, fit.zfar);

    rx::graph::RenderGraph graph;
    declareGraph(graph, *app);
    rx::graph::CompileInfo compileInfo;
    compileInfo.swapchainWidth = kRenderWidth;
    compileInfo.swapchainHeight = kRenderHeight;
    compileInfo.swapchainFormat = kBackbufferFormat;
    compileInfo.backbufferFinalLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
    graph.compile(compileInfo);
    app->executor->realize(graph);

    const VkDevice vkDevice = app->device->device();
    VkImage offscreenImage = VK_NULL_HANDLE;
    VkDeviceMemory offscreenMemory = VK_NULL_HANDLE;
    VkImageView offscreenView = VK_NULL_HANDLE;
    auto destroyRawResources = [&]() {
        if (offscreenView != VK_NULL_HANDLE) {
            vkDestroyImageView(vkDevice, offscreenView, nullptr);
        }
        if (offscreenImage != VK_NULL_HANDLE) {
            vkDestroyImage(vkDevice, offscreenImage, nullptr);
        }
        if (offscreenMemory != VK_NULL_HANDLE) {
            vkFreeMemory(vkDevice, offscreenMemory, nullptr);
        }
    };

    VkImageCreateInfo imageInfo{};
    imageInfo.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
    imageInfo.imageType = VK_IMAGE_TYPE_2D;
    imageInfo.format = kBackbufferFormat;
    imageInfo.extent = {kRenderWidth, kRenderHeight, 1};
    imageInfo.mipLevels = 1;
    imageInfo.arrayLayers = 1;
    imageInfo.samples = VK_SAMPLE_COUNT_1_BIT;
    imageInfo.tiling = VK_IMAGE_TILING_OPTIMAL;
    imageInfo.usage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT;
    imageInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    imageInfo.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    if (vkCreateImage(vkDevice, &imageInfo, nullptr, &offscreenImage) != VK_SUCCESS) {
        RX_LOG_ERROR("rx_conformance_render: vkCreateImage(offscreen target) failed");
        destroyRawResources();
        destroyApp(*app);
        return 1;
    }
    VkMemoryRequirements memReq{};
    vkGetImageMemoryRequirements(vkDevice, offscreenImage, &memReq);
    VkPhysicalDeviceMemoryProperties memProps{};
    vkGetPhysicalDeviceMemoryProperties(app->device->physicalDevice(), &memProps);
    uint32_t memoryTypeIndex = UINT32_MAX;
    for (uint32_t i = 0; i < memProps.memoryTypeCount; ++i) {
        if ((memReq.memoryTypeBits & (1U << i)) != 0U &&
            (memProps.memoryTypes[i].propertyFlags & VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT) != 0U) {
            memoryTypeIndex = i;
            break;
        }
    }
    if (memoryTypeIndex == UINT32_MAX) {
        RX_LOG_ERROR("rx_conformance_render: no device-local memory type found for the offscreen target");
        destroyRawResources();
        destroyApp(*app);
        return 1;
    }
    VkMemoryAllocateInfo memAllocInfo{};
    memAllocInfo.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    memAllocInfo.allocationSize = memReq.size;
    memAllocInfo.memoryTypeIndex = memoryTypeIndex;
    if (vkAllocateMemory(vkDevice, &memAllocInfo, nullptr, &offscreenMemory) != VK_SUCCESS) {
        RX_LOG_ERROR("rx_conformance_render: vkAllocateMemory(offscreen target) failed");
        destroyRawResources();
        destroyApp(*app);
        return 1;
    }
    if (vkBindImageMemory(vkDevice, offscreenImage, offscreenMemory, 0) != VK_SUCCESS) {
        RX_LOG_ERROR("rx_conformance_render: vkBindImageMemory(offscreen target) failed");
        destroyRawResources();
        destroyApp(*app);
        return 1;
    }
    VkImageViewCreateInfo viewInfo{};
    viewInfo.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
    viewInfo.image = offscreenImage;
    viewInfo.viewType = VK_IMAGE_VIEW_TYPE_2D;
    viewInfo.format = kBackbufferFormat;
    viewInfo.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
    viewInfo.subresourceRange.levelCount = 1;
    viewInfo.subresourceRange.layerCount = 1;
    if (vkCreateImageView(vkDevice, &viewInfo, nullptr, &offscreenView) != VK_SUCCESS) {
        RX_LOG_ERROR("rx_conformance_render: vkCreateImageView(offscreen target) failed");
        destroyRawResources();
        destroyApp(*app);
        return 1;
    }

    auto cmdCtx =
        rx::rhi::CommandContext::create(vkDevice, app->device->graphicsQueue(), app->device->graphicsQueueFamily());
    if (!cmdCtx.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: CommandContext::create failed");
        destroyRawResources();
        destroyApp(*app);
        return 1;
    }

    const VkExtent2D extent{kRenderWidth, kRenderHeight};
    cmdCtx->runOnce(
        [&](VkCommandBuffer cmd) { app->executor->execute(graph, cmd, offscreenImage, offscreenView, extent); });

    auto readback = app->allocator->createHostVisibleBuffer(kRenderPixelBytes, VK_BUFFER_USAGE_TRANSFER_DST_BIT);
    bool gateOk = readback.has_value();
    std::vector<uint8_t> pixels;
    if (readback.has_value()) {
        cmdCtx->runOnce([&](VkCommandBuffer cmd) {
            VkBufferImageCopy region{};
            region.imageSubresource.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
            region.imageSubresource.layerCount = 1;
            region.imageExtent = {kRenderWidth, kRenderHeight, 1};
            vkCmdCopyImageToBuffer(cmd, offscreenImage, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, readback->handle(), 1,
                                    &region);
        });
        readback->invalidate();
        pixels.resize(static_cast<size_t>(kRenderPixelBytes));
        std::memcpy(pixels.data(), readback->mappedData(), pixels.size());
        gateOk = canonicalizeToRgba8(pixels, kBackbufferFormat);
    } else {
        RX_LOG_ERROR("rx_conformance_render: createHostVisibleBuffer(readback) failed");
    }
    // MUST be destroyed before destroyApp() below tears down the Allocator/
    // Device it was created from -- unlike sample08_gltf_viewer's own
    // captureFrame() lambda (where the equivalent local goes out of scope
    // at the end of EACH lambda call, always before that same sample's own
    // later destroyApp()), this tool renders only once and had no such
    // lambda scope to rely on -- reproduced directly this task as a real
    // "Allocator::destroyAll: torn down with outstanding... allocations"
    // error immediately followed by a segfault at process exit (the same
    // class of teardown-ordering bug this stage's own review history keeps
    // finding -- see sample_08_gltf_viewer's own --quit-during-load comment
    // for the analogous CommandContext-vs-Device lesson).
    readback.reset();

    if (!args->dumpPath.empty() && !pixels.empty()) {
        if (!rx::samples::writeRgba8Png(args->dumpPath, kRenderWidth, kRenderHeight, pixels.data())) {
            RX_LOG_ERROR("rx_conformance_render: --dump '{}' failed to write", args->dumpPath);
        }
    }

    if (gateOk) {
        auto reference = rx::samples::loadRgba8Png(referencePath);
        if (!reference.has_value()) {
            RX_LOG_ERROR("rx_conformance_render: failed to load committed reference '{}'", referencePath.string());
            gateOk = false;
        } else {
            rx::samples::GateResult gate = rx::samples::compareToReference(
                pixels.data(), kRenderWidth, kRenderHeight, reference->rgba8.data(), reference->width,
                reference->height, model->perChannelToleranceOutOf255, model->failingPixelBudgetFraction);
            RX_LOG_INFO(
                "rx_conformance_render: {} gate: driver='{}' failingPixels={}/{} ({:.4f}%) tolerance=+-{}/255 "
                "budget<{:.2f}% pass={}",
                model->name, deviceProps.deviceName, gate.failingPixelCount, gate.totalPixelCount,
                gate.failingPixelFraction * 100.0, model->perChannelToleranceOutOf255,
                model->failingPixelBudgetFraction * 100.0, gate.passed);
            if (!gate.passed) {
                RX_LOG_ERROR(
                    "rx_conformance_render: {} gate FAILED (first mismatch at ({},{}), delta rgba=({},{},{},{}))",
                    model->name, gate.firstMismatchX, gate.firstMismatchY, gate.firstMismatchDelta[0],
                    gate.firstMismatchDelta[1], gate.firstMismatchDelta[2], gate.firstMismatchDelta[3]);
                gateOk = false;
            }
        }
    }

    vkDeviceWaitIdle(vkDevice);
    cmdCtx.reset();
    destroyRawResources();
    destroyApp(*app);

    if (args->validate && app->context->hasValidationErrors()) {
        RX_LOG_ERROR("rx_conformance_render: Vulkan validation layer reported errors during this run");
        gateOk = false;
    }

    if (gateOk) {
        RX_LOG_INFO("rx_conformance_render: {} conformance gate PASSED", model->name);
        return 0;
    }
    RX_LOG_ERROR("rx_conformance_render: {} conformance gate FAILED", model->name);
    return 1;
}
