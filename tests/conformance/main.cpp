template <typename T>
bool setMaterialParam(std::vector<uint8_t>& blob, const std::vector<rx::material::MaterialParamInfo>& params,
                      const char* name, const T& value) {
    for (const auto& p : params) {
        if (p.name == name) {
            if (p.size != sizeof(T)) {
                RX_LOG_ERROR("rx_conformance_render: material param '{}' reflected size {} != sizeof(T) {}", name,
                             p.size, sizeof(T));
                return false;
            }
            std::memcpy(blob.data() + p.offset, &value, sizeof(T));
            return true;
        }
    }
    RX_LOG_ERROR("rx_conformance_render: material param '{}' not found in reflection", name);
    return false;
}

// [Discrimination proof, --perturb-roughness-value] Unlike
// setMaterialParam() above, ABSENCE is not an error here -- Unlit
// materials have no `roughnessFactor` param at all, and that is a
// legitimate, expected case this function must silently no-op for
// (returns false, no log) rather than treating as a setup bug.
//
// ABSOLUTE OVERRIDE (blob := value), NOT relative to whatever the
// material already had -- TWO relative mechanisms were tried first and
// both found INSUFFICIENT, for complementary "fixed point" reasons this
// header comment records rather than silently discarding the finding:
//  (1) MULTIPLICATIVE (current *= factor): MetalRoughSpheres' own
//      roughness=0.0 column (the grid's own mirror-smooth, most-
//      visually-distinctive spheres) is a fixed point under
//      multiplication (`0 * anyFactor == 0`) -- that whole column stayed
//      bit-identical regardless of factor magnitude.
//  (2) ADDITIVE, clamped (current = clamp(current + delta, 0, 1)):
//      MetalRoughSpheres' own single shared material's own
//      `roughnessFactor` is ALREADY at glTF's neutral default (1.0 --
//      the model's real per-sphere roughness VARIATION is baked into
//      `Spheres_MetalRough.png`'s own texture data, `roughnessFactor`
//      is just the spec's multiplier on top of it); clamping at the
//      SAME boundary (1.0) the value already sits AT is *itself* the new
//      fixed point -- reproduced directly this task (0.3/0.5/0.6/0.8
//      delta all produced the IDENTICAL, unperturbed render).
// An absolute override has no such fixed point for any starting value
// materially different from the chosen override (0.02 -- see this
// function's own caller).
bool overrideFloatMaterialParamIfPresent(std::vector<uint8_t>& blob,
                                          const std::vector<rx::material::MaterialParamInfo>& params,
                                          const char* name, float value) {
    for (const auto& p : params) {
        if (p.name == name && p.size == sizeof(float)) {
            std::memcpy(blob.data() + p.offset, &value, sizeof(float));
            return true;
        }
    }
    return false;
}

rx::material::AlphaMode toMaterialAlphaMode(rx::asset::AlphaMode mode) {
    switch (mode) {
        case rx::asset::AlphaMode::Opaque:
            return rx::material::AlphaMode::Opaque;
        case rx::asset::AlphaMode::Mask:
            return rx::material::AlphaMode::Mask;
        case rx::asset::AlphaMode::Blend:
            return rx::material::AlphaMode::Blend;
    }
    return rx::material::AlphaMode::Opaque;
}

uint32_t resolveTextureIndex(rx::asset::TextureCache& textures, const rx::asset::TextureRef& ref,
                              rx::asset::TextureRole role) {
    if (!ref.present) {
        return textures.resolve(textures.fallbackHandle(role)).bindlessIndex;
    }
    return textures.resolve(ref.handle).bindlessIndex;
}

uint32_t resolveSamplerIndex(rx::asset::TextureCache& textures, const rx::asset::TextureRef& ref,
                              uint32_t fallbackIndex) {
    std::optional<uint32_t> index = textures.getOrCreateSamplerBindlessIndex(ref.sampler);
    return index.value_or(fallbackIndex);
}

std::array<float, 4> uvTransformParam(const rx::asset::TextureRef& ref) {
    return {ref.uvOffset.x, ref.uvOffset.y, ref.uvScale.x, ref.uvScale.y};
}

