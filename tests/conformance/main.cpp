// [Copied from samples/08_gltf_viewer's own basePathDirectory() idiom]
// The directory the running binary itself lives in (SDL_GetBasePath()) --
// used ONLY for this process's own pipeline-cache file (a build-tree-
// relative, preset-agnostic location); every glTF/shader/reference asset
// this tool reads is resolved via RX_REPO_ROOT_DIR instead (this file's
// own top comment / CMakeLists.txt's own header comment explain why this
// tool, unlike a redistributed sample, reads straight from the source
// tree).
std::filesystem::path basePathDirectory() {
    const char* basePath = SDL_GetBasePath();
    if (basePath == nullptr) {
        RX_LOG_WARN("rx_conformance_render: SDL_GetBasePath failed ({}); using the current directory instead",
                    SDL_GetError());
        return ".";
    }
    return std::filesystem::path(basePath);
}

std::unique_ptr<App> makeApp(bool validate) {
    auto app = std::make_unique<App>();

    auto window = rx::platform::Window::create("rx_conformance_render", static_cast<int>(kRenderWidth),
                                                 static_cast<int>(kRenderHeight), /*visible=*/false);
    if (!window.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: Window::create failed: no display backend available");
        return nullptr;
    }
    auto extensions = window->requiredVulkanInstanceExtensions();
    if (extensions.empty()) {
        RX_LOG_ERROR("rx_conformance_render: video driver reports no Vulkan surface extensions");
        return nullptr;
    }
    auto context = rx::rhi::Context::create(extensions, validate);
    if (!context.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: Context::create failed");
        return nullptr;
    }
    app->window.emplace(std::move(*window));
    app->context.emplace(std::move(*context));

    app->surface = app->window->createVulkanSurface(app->context->instance());
    if (app->surface == VK_NULL_HANDLE) {
        RX_LOG_ERROR("rx_conformance_render: createVulkanSurface failed");
        return nullptr;
    }

    auto device = rx::rhi::Device::create(*app->context, app->surface);
    if (!device.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: Device::create failed");
        return nullptr;
    }
    app->device.emplace(std::move(*device));

    auto allocator = rx::rhi::Allocator::create(*app->context, *app->device);
    if (!allocator.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: Allocator::create failed");
        return nullptr;
    }
    app->allocator.emplace(std::move(*allocator));

    auto uploader = rx::rhi::Uploader::create(*app->allocator, *app->device);
    if (!uploader.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: Uploader::create failed");
        return nullptr;
    }
    app->uploader.emplace(std::move(*uploader));

    rx::rhi::BindlessTable::Capacities capacities{/*sampledImages=*/256, /*samplers=*/16, /*storageBuffers=*/8};
    capacities.comparisonSamplers = 1;
    capacities.cubeImages = 4;
    auto bindless =
        rx::rhi::BindlessTable::create(app->device->physicalDevice(), app->device->device(), capacities);
    if (!bindless.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: BindlessTable::create failed");
        return nullptr;
    }
    app->bindless.emplace(std::move(*bindless));
    app->deletionQueue.emplace();

    const std::filesystem::path sharedShaderDir = std::filesystem::path(RX_REPO_ROOT_DIR) / "shaders" / "material";
    // Pipeline cache lives next to the BINARY (SDL_GetBasePath(), matching
    // samples/08_gltf_viewer's own `basePath / "gltf_viewer_pipeline.cache"`
    // convention) -- NOT under a hardcoded "<repo>/build/" path (which
    // assumed a single, specific preset's own build directory name/layout
    // and would be wrong for any other preset).
    app->materialSystem = rx::material::MaterialSystem::create(
        *app->device, *app->bindless, basePathDirectory() / "rx_conformance_render_pipeline.cache", sharedShaderDir);
    if (app->materialSystem == nullptr) {
        RX_LOG_ERROR("rx_conformance_render: MaterialSystem::create failed");
        return nullptr;
    }

    app->geometryPool = rx::asset::GeometryPool::create(*app->allocator, *app->device, *app->uploader);
    if (app->geometryPool == nullptr) {
        RX_LOG_ERROR("rx_conformance_render: GeometryPool::create failed");
        return nullptr;
    }

    app->textureCache = rx::asset::TextureCache::create(*app->allocator, *app->device, *app->uploader,
                                                          *app->bindless, *app->deletionQueue);
    if (app->textureCache == nullptr) {
        RX_LOG_ERROR("rx_conformance_render: TextureCache::create failed");
        return nullptr;
    }

    app->registry = std::make_unique<rx::asset::Registry>();
    app->scheduler = rx::task::Scheduler::create();
    if (app->scheduler == nullptr) {
        RX_LOG_ERROR("rx_conformance_render: Scheduler::create failed");
        return nullptr;
    }
    app->executor = rx::graph::Executor::create(*app->device, *app->scheduler);
    if (app->executor == nullptr) {
        RX_LOG_ERROR("rx_conformance_render: Executor::create failed");
        return nullptr;
    }

    VkSamplerCreateInfo samplerInfo{};
    samplerInfo.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
    samplerInfo.magFilter = VK_FILTER_LINEAR;
    samplerInfo.minFilter = VK_FILTER_LINEAR;
    samplerInfo.addressModeU = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    samplerInfo.addressModeV = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    samplerInfo.addressModeW = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    samplerInfo.maxLod = VK_LOD_CLAMP_NONE;
    if (vkCreateSampler(app->device->device(), &samplerInfo, nullptr, &app->defaultSampler) != VK_SUCCESS) {
        RX_LOG_ERROR("rx_conformance_render: vkCreateSampler (default sampler) failed");
        return nullptr;
    }
    app->defaultSamplerHandle = app->bindless->registerSampler(app->defaultSampler);
    if (!app->defaultSamplerHandle.isValid()) {
        RX_LOG_ERROR("rx_conformance_render: BindlessTable::registerSampler (default sampler) failed");
        return nullptr;
    }

    auto compiler = rx::shader::Compiler::create();
    if (!compiler.has_value()) {
        RX_LOG_ERROR("rx_conformance_render: rx::shader::Compiler::create failed");
        return nullptr;
    }
    const std::filesystem::path repoRoot(RX_REPO_ROOT_DIR);
    if (!buildTonemapPipeline(app->device->device(), *compiler, app->bindless->descriptorSetLayout(),
                              repoRoot / "shaders" / "multipass" / "tonemap.vert.slang",
                              repoRoot / "shaders" / "conformance" / "tonemap_linear.frag.slang", app->tonemapPass)) {
        return nullptr;
    }

    app->scene.emplace([](rx::asset::MeshHandle) { return rx::asset::AABB{}; });

    return app;
}

